const fs = require('fs');
const path = require('path');
const mongoose = require('mongoose');

// Resolve MongoDB connection URI
function getMongoUri() {
  const envPath = path.join(__dirname, '..', '.env');
  if (fs.existsSync(envPath)) {
    const envContent = fs.readFileSync(envPath, 'utf-8');
    const match = envContent.match(/MONGO_URI=(.+)/);
    if (match && match[1]) {
      return match[1].trim();
    }
  }
  return process.env.MONGO_URI || 'mongodb+srv://loly:ZJqlB0M53fnwVHyY@avercare.hgfk9wr.mongodb.net/tt';
}

/**
 * Main cleanup logic to revert all modifications made by tests.
 * Safe guard: Never deletes official admin user or @sports.org seeded players.
 */
async function cleanTestData(customMongoUri) {
  const uri = customMongoUri || getMongoUri();
  const shouldDisconnect = !mongoose.connection.readyState;

  if (mongoose.connection.readyState === 0) {
    console.log('🔗 Connecting to database for test cleanup...');
    await mongoose.connect(uri);
  }

  const db = mongoose.connection.db;
  const usersCollection = db.collection('users');
  const tournamentsCollection = db.collection('tournaments');
  const matchesCollection = db.collection('matches');

  console.log('🧹 Purging test artifacts and reverting test changes...');

  // 1. Identify test users to delete (preserving admin and seeded @sports.org roster)
  const testUsersFilter = {
    $and: [
      { email: { $not: /@sports\.org$/i } },
      { email: { $ne: 'lovely.kumar@testingxperts.com' } },
      { email: { $ne: 'admin@ttportal.com' } },
      {
        $or: [
          { email: /@example\.com$/i },
          { email: /@ttsports\.com$/i },
          { email: /^player_/i },
          { email: /^staff_/i },
          { email: /^test\./i },
          { firstName: /^Alex[0-9]+/i },
          { firstName: /^Staff[0-9]+/i },
        ],
      },
    ],
  };

  const testUsers = await usersCollection.find(testUsersFilter).toArray();
  const testUserIds = testUsers.map((u) => u._id.toString());
  const testUserObjectIds = testUsers.map((u) => u._id);

  let deletedUsersCount = 0;
  if (testUserObjectIds.length > 0) {
    const res = await usersCollection.deleteMany({ _id: { $in: testUserObjectIds } });
    deletedUsersCount = res.deletedCount;
  }

  // 2. Identify test tournaments to delete
  const testTournamentsFilter = {
    $or: [
      { name: /^test tournament/i },
      { name: /^Championship [0-9]+/i },
      { name: /^TT Solo Cup/i },
      { name: /^Cricket Premier/i },
      { name: /^Table Tennis Wave/i },
      { name: /[0-9]{12,}/ }, // Contains timestamp suffix like 17918...
      { description: /Auto-generated by test/i },
    ],
  };

  const testTournaments = await tournamentsCollection.find(testTournamentsFilter).toArray();
  const testTournamentIds = testTournaments.map((t) => t._id.toString());
  const testTournamentObjectIds = testTournaments.map((t) => t._id);

  let deletedTournamentsCount = 0;
  if (testTournamentObjectIds.length > 0) {
    const res = await tournamentsCollection.deleteMany({ _id: { $in: testTournamentObjectIds } });
    deletedTournamentsCount = res.deletedCount;
  }

  // 3. Delete all matches associated with test tournaments or test users
  const testMatchesFilter = {
    $or: [
      { tournamentId: { $in: testTournamentIds } },
      { tournamentName: /^test tournament/i },
      { tournamentName: /^Championship [0-9]+/i },
      { tournamentName: /^TT Solo Cup/i },
      { tournamentName: /^Cricket Premier/i },
      { tournamentName: /^Table Tennis Wave/i },
      { playerAId: { $in: testUserIds } },
      { playerBId: { $in: testUserIds } },
    ],
  };

  const deleteMatchesRes = await matchesCollection.deleteMany(testMatchesFilter);
  const deletedMatchesCount = deleteMatchesRes.deletedCount;

  // 4. Clean any orphaned registrations in persistent showcase tournaments
  if (testUserIds.length > 0) {
    await tournamentsCollection.updateMany(
      {},
      {
        $pull: {
          participants: { $in: testUserIds },
          teams: { 'members.userId': { $in: testUserIds } },
        },
      }
    );
  }

  console.log('======================================================');
  console.log('✨ Test Cleanup Completed Successfully:');
  console.log(`- Deleted Test Users:        ${deletedUsersCount}`);
  console.log(`- Deleted Test Tournaments:  ${deletedTournamentsCount}`);
  console.log(`- Deleted Test Matches:      ${deletedMatchesCount}`);
  console.log('✨ Seeded Roster (@sports.org) and Admin remain intact.');
  console.log('======================================================\n');

  if (shouldDisconnect) {
    await mongoose.disconnect();
  }

  return {
    deletedUsersCount,
    deletedTournamentsCount,
    deletedMatchesCount,
  };
}

if (require.main === module) {
  cleanTestData()
    .then(() => process.exit(0))
    .catch((err) => {
      console.error('❌ Cleanup failed:', err);
      process.exit(1);
    });
}

module.exports = { cleanTestData };
